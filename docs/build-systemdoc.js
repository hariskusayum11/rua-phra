const TOTAL_W = 9360; // 6.5in content width at DXA

function makeTable(headers, rows, widths) {
  const sum = widths.reduce((a, b) => a + b, 0);
  const scaled = widths.map((w) => Math.round((w / sum) * TOTAL_W));
  scaled[scaled.length - 1] = TOTAL_W - scaled.slice(0, -1).reduce((a, b) => a + b, 0);

  const cell = (text, i, opts = {}) =>
    new TableCell({
      width: { size: scaled[i], type: WidthType.DXA },
      shading: opts.head ? { type: ShadingType.CLEAR, fill: GREEN } : undefined,
      margins: { top: 90, bottom: 90, left: 120, right: 120 },
      children: [
        new Paragraph({
          spacing: { after: 0, line: 270 },
          children: [new TextRun({
            text,
            font: opts.mono ? "Consolas" : FONT,
            size: opts.head ? 19 : 19,
            bold: opts.head,
            color: opts.head ? "FFFFFF" : INK,
          })],
        }),
      ],
    });

  return new Table({
    columnWidths: scaled,
    width: { size: TOTAL_W, type: WidthType.DXA },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 4, color: RULE },
      bottom: { style: BorderStyle.SINGLE, size: 4, color: RULE },
      left: { style: BorderStyle.SINGLE, size: 4, color: RULE },
      right: { style: BorderStyle.SINGLE, size: 4, color: RULE },
      insideHorizontal: { style: BorderStyle.SINGLE, size: 4, color: RULE },
      insideVertical: { style: BorderStyle.SINGLE, size: 4, color: RULE },
    },
    rows: [
      new TableRow({
        tableHeader: true,
        children: headers.map((h, i) => cell(h, i, { head: true })),
      }),
      ...rows.map((r) => new TableRow({
        children: r.map((c, i) => cell(String(c), i, { mono: /^[/A-Za-z0-9_.\[\]-]+$/.test(String(c)) && String(c).length > 2 })),
      })),
    ],
  });
}

